export const calculateToeicScore = (rawScore: number, type: 'LC' | 'RC'): number => {
    const table = type === 'LC' ? LC_CONVERSION : RC_CONVERSION;
    // Ensure rawScore is within bounds (0-100)
    const scoreIndex = Math.max(0, Math.min(rawScore, 100));
    return table[scoreIndex] || 5;
};
